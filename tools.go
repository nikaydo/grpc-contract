//go:build tools

// Этот файл фиксирует версии генераторов protobuf.
//
// Обычной практикой является установка генераторов через `go install
// <путь>@latest`, но тогда версия в CI и на рабочей машине разъезжается:
// сгенерированный код отличается только в комментарии с версией, и проверка
// «совпадает ли код с .proto» начинает падать без причины.
//
// Проблема решается тем, что генераторы объявлены здесь как зависимости
// модуля: go mod tidy фиксирует их версии в go.mod, а task install ставит
// именно их.
package tools

import (
	// Генератор Go-кода по .proto.
	_ "google.golang.org/protobuf/cmd/protoc-gen-go"

	// Генератор gRPC-клиентов и серверов.
	_ "google.golang.org/grpc/cmd/protoc-gen-go-grpc"
)
